#!/usr/bin/env node
/**
 * Emit the catalog mirror as SQL from the same shared records the game uses.
 *
 * The runtime never reads this file: it exists so a Neon/edge deployment can
 * hold the catalog for admin tooling and reporting without a second, drifting
 * copy of the data. Re-run it whenever the catalog changes.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { EXPANSION_ITEMS } from '../shared/catalog/expansion.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
const outFile = path.resolve(here, '..', 'migrations', 'catalog-seed.generated.sql');

const q = (value) => `'${String(value).replace(/'/g, "''")}'`;
const json = (value) => `${q(JSON.stringify(value))}::jsonb`;

const rows = EXPANSION_ITEMS.map((item) =>
  [
    q(item.id),
    q(item.name),
    q(item.category),
    q(item.subcategory),
    q(item.description),
    q(item.model.kind),
    json(item.model.params ?? {}),
    q(`/${item.previewBase}.png`),
    q(item.previewBase),
    item.price,
    q(item.currency),
    q(item.layer),
    item.size[0],
    item.size[1],
    json(item.colors),
    json(item.themes ?? []),
    q(item.placement),
    q(item.availability),
    item.version,
  ].join(', ')
);

const sql = `-- Generated by scripts/export-catalog-sql.mjs — do not edit by hand.
-- Mirrors shared/catalog/expansion.mjs (${EXPANSION_ITEMS.length} items).

begin;

insert into catalog_items (
  id, name, category, subcategory, description, model_kind, model_params,
  preview_path, preview_r2_key, price, currency, layer, footprint_width,
  footprint_depth, color_variants, themes, placement, availability, asset_version
) values
${rows.map((row) => `  (${row})`).join(',\n')}
on conflict (id) do update set
  name = excluded.name,
  category = excluded.category,
  subcategory = excluded.subcategory,
  description = excluded.description,
  model_kind = excluded.model_kind,
  model_params = excluded.model_params,
  preview_path = excluded.preview_path,
  preview_r2_key = excluded.preview_r2_key,
  price = excluded.price,
  currency = excluded.currency,
  layer = excluded.layer,
  footprint_width = excluded.footprint_width,
  footprint_depth = excluded.footprint_depth,
  color_variants = excluded.color_variants,
  themes = excluded.themes,
  placement = excluded.placement,
  availability = excluded.availability,
  asset_version = excluded.asset_version,
  updated_at = now();

commit;
`;

fs.writeFileSync(outFile, sql);
console.log(`Wrote ${EXPANSION_ITEMS.length} catalog rows to ${path.relative(process.cwd(), outFile)}`);
