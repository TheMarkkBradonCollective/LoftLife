#!/usr/bin/env node
/**
 * Build a static gallery of every catalog preview, grouped by category, so the
 * rendered asset set can be reviewed without launching the game.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { CATALOG_CATEGORIES, EXPANSION_ITEMS } from '../shared/catalog/expansion.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '..');
const manifest = JSON.parse(fs.readFileSync(path.join(root, 'shared/catalog/preview-manifest.json'), 'utf8'));
const out = path.join(root, 'docs', 'catalog-gallery.html');

const esc = (value) =>
  String(value).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

const sections = CATALOG_CATEGORIES.map((category) => {
  const items = EXPANSION_ITEMS.filter((item) => item.category === category.id);
  if (!items.length) return '';
  const cards = items
    .map((item) => {
      const record = manifest.items[item.id];
      const image = record?.previews?.[0]?.path ?? `/${item.previewBase}.png`;
      return `<figure><img src="../public${esc(image)}" alt="${esc(item.name)}" loading="lazy"><figcaption>${esc(
        item.name
      )}<span>${esc(item.subcategory)} · ${item.size[0]}×${item.size[1]} m · 元${item.price}</span></figcaption></figure>`;
    })
    .join('\n');
  return `<section><h2>${esc(category.label)} <small>${items.length} pieces</small></h2><div class="grid">${cards}</div></section>`;
}).join('\n');

const total = Object.keys(manifest.items).length;
const images = Object.values(manifest.items).reduce((sum, record) => sum + record.previews.length, 0);

fs.writeFileSync(
  out,
  `<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>LoftLife catalog — rendered asset gallery</title>
<style>
  :root{color-scheme:dark}
  body{margin:0;background:#101216;color:#e8ecf1;font:14px/1.5 ui-sans-serif,system-ui,sans-serif}
  header{padding:32px 28px 12px;border-bottom:1px solid #262b33}
  h1{margin:0;font-size:22px;letter-spacing:-0.01em}
  header p{margin:6px 0 0;color:#98a2b3;font-size:13px}
  section{padding:20px 28px 8px}
  h2{font-size:15px;margin:0 0 12px;text-transform:uppercase;letter-spacing:.14em;color:#c9d3df}
  h2 small{font-weight:400;color:#6f7a89;letter-spacing:0;text-transform:none;font-size:12px;margin-left:6px}
  .grid{display:grid;grid-template-columns:repeat(auto-fill,minmax(168px,1fr));gap:12px}
  figure{margin:0;background:#181c22;border:1px solid #232830;border-radius:12px;padding:10px}
  figure img{width:100%;aspect-ratio:1;object-fit:contain;display:block;background:radial-gradient(circle at 50% 38%,#2a3038,#15181d 70%);border-radius:8px}
  figcaption{font-size:11px;margin-top:8px;line-height:1.35}
  figcaption span{display:block;color:#77828f;font-size:10px;margin-top:2px}
</style></head>
<body>
<header>
  <h1>LoftLife catalog — rendered from the in-game models</h1>
  <p>${total} items · ${images} transparent PNGs · generated by <code>scripts/build-catalog-gallery.mjs</code>. Each tile is that item's actual preview file, produced by rendering the same Three.js model the build tool places.</p>
</header>
${sections}
</body></html>
`
);
console.log(`Gallery: ${total} items, ${images} renders → ${path.relative(process.cwd(), out)}`);
